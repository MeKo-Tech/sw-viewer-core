// Builds the library and copies it into an app as a vendored, generated copy:
//
//   node tools/sync.ts ../moin-bridge/src/vendor/sw-viewer-core
//
// The target directory is replaced completely. Each file gets a header naming the
// source commit, so a diff in the app shows which decoder version it runs.

import { execFileSync } from "node:child_process";
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const target = process.argv[2];
if (!target) {
  console.error("usage: node tools/sync.ts <target-dir>");
  process.exit(2);
}
const dest = resolve(target);

const git = (...args: string[]) => {
  try {
    return execFileSync("git", args, { cwd: root, encoding: "utf8" }).trim();
  } catch {
    return "";
  }
};
const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8")) as { version: string };
const commit = git("rev-parse", "--short=12", "HEAD") || "unknown";
const dirty = git("status", "--porcelain", "--", "src") !== "";
const source = `MeKo-Tech/sw-viewer-core v${pkg.version} @ ${commit}${dirty ? " (uncommitted changes)" : ""}`;

const lib = join(root, "dist", "lib");
rmSync(lib, { recursive: true, force: true });
execFileSync(process.execPath, [join(root, "node_modules/typescript/bin/tsc"), "-p", join(root, "tsconfig.build.json")], {
  stdio: "inherit",
});

rmSync(dest, { recursive: true, force: true });
mkdirSync(dest, { recursive: true });
const header = `// GENERATED by sw-viewer-core tools/sync.ts. Do not edit.\n// Source: ${source}\n`;
const files = readdirSync(lib).filter((f) => (f.endsWith(".js") || f.endsWith(".d.ts")) && f !== "worker.d.ts");
for (const f of files) {
  writeFileSync(join(dest, f), header + readFileSync(join(lib, f), "utf8"));
}
writeFileSync(
  join(dest, "README.md"),
  `# sw-viewer-core (vendored)\n\nGenerated copy of the SolidWorks display-mesh decoder.\nSource: ${source}\n\n` +
    "Do not edit these files. Change the decoder in `MeKo-Tech/sw-viewer-core` and run\n" +
    "`node tools/sync.ts <this directory>` there.\n",
);
console.log(`synced ${files.length} files from ${source} to ${dest}`);
